import importlib.util,json,tempfile,unittest,hashlib
from pathlib import Path
from unittest.mock import patch
from zipfile import ZipFile

ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('desktop_release_package',ROOT/'scripts/package-desktop-release.py')
packager=importlib.util.module_from_spec(spec);spec.loader.exec_module(packager)


class ReleasePackagingTests(unittest.TestCase):
    def run_package(self,maximum=None):
        temp=tempfile.TemporaryDirectory();self.addCleanup(temp.cleanup)
        folder=Path(temp.name);app=folder/'ScreenTo3D-1.0.0';app.mkdir()
        (app/'build-manifest.json').write_text(json.dumps(dict(product_version='1.0.0',source_commit='owned-fixture')))
        for index in range(4):(app/f'owned-{index}.bin').write_bytes(bytes(range(256)))
        (app/'__pycache__').mkdir();(app/'__pycache__/owned.pyc').write_bytes(b'generated by QA')
        licenses=app/'packages/packaging/licenses';(licenses/'__pycache__').mkdir(parents=True)
        (licenses/'__pycache__/__init__.cpython-313.pyc').write_bytes(b'private build path fixture')
        (licenses/'COPYING.LIB').write_bytes(b'copyright notice must survive')
        output=folder/'assets'
        with patch.object(packager,'MAX_ASSET',maximum or packager.MAX_ASSET):packager.package(app,output,None)
        manifest=json.loads((output/'release-manifest.json').read_text())
        seen=set()
        for asset in manifest['assets']:
            archive=output/asset['name']
            self.assertEqual(packager.digest(archive),asset['sha256'])
            with ZipFile(archive) as zip:
                for entry in zip.infolist():
                    self.assertNotIn(entry.filename,seen);seen.add(entry.filename)
                    self.assertEqual(zip.read(entry), (folder/entry.filename).read_bytes())
        self.assertEqual(len(seen),6)
        self.assertIn(app.name+'/packages/packaging/licenses/COPYING.LIB',seen)
        self.assertFalse(any('__pycache__' in name or name.endswith(('.pyc','.pyo')) for name in seen))
        return manifest

    def test_one_archive_has_plain_filename_and_matching_manifest(self):
        manifest=self.run_package()
        self.assertEqual([a['name'] for a in manifest['assets']],['ScreenTo3D-1.0.0-windows-x64.zip'])

    def test_multiple_archives_keep_numbered_names_and_disjoint_contents(self):
        manifest=self.run_package(32*1024**2+384)
        self.assertGreater(len(manifest['assets']),1)
        for index,asset in enumerate(manifest['assets'],1):
            self.assertEqual(asset['name'],f'ScreenTo3D-1.0.0-windows-x64-part{index:02d}.zip')

    def test_upstream_failure_prevents_publishing_assets(self):
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder);app=root/'ScreenTo3D-1.0.0';app.mkdir()
            (app/'build-manifest.json').write_text(json.dumps(dict(product_version='1.0.0',source_commit='fixture',upstream_downloads=['owned'],desktop_components='on-demand official downloads')))
            catalog=app/'v1/screento3d_app';catalog.mkdir(parents=True)
            (catalog/'upstream_sources.json').write_text(json.dumps(dict(artifacts={'owned':{}})))
            with patch('screento3d_app.upstream_check.check',side_effect=OSError('Pinned publisher unavailable')),self.assertRaises(OSError):
                packager.package(app,root/'assets',None)
            self.assertFalse((root/'assets').exists())
            with patch('screento3d_app.upstream_check.check',return_value=[dict(component='owned',status=206)]) as checked:
                packager.package(app,root/'assets',None)
                checked.assert_called_once()
            manifest=json.loads((root/'assets/release-manifest.json').read_text())
            self.assertTrue(all(asset['kind']=='application' for asset in manifest['assets']))
            self.assertEqual(manifest['upstream_download_checks'],[dict(component='owned',status=206)])

    def test_offline_model_packs_are_verified_and_preferred_without_network(self):
        from screento3d_app import optional_models as models
        spec=importlib.util.spec_from_file_location('portable_model_bundling',ROOT/'scripts/build-desktop-portable.py')
        builder=importlib.util.module_from_spec(spec);spec.loader.exec_module(builder)
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder);source=root/'input';source.mkdir();app=root/'app';app.mkdir()
            fixtures={}
            for key in ('da2-base','vda-small'):
                data=key.encode();filename=key+'.zip';(source/filename).write_bytes(data)
                fixtures[key]=models.Pack(key,filename,len(data),hashlib.sha256(data).hexdigest(),'')
            with patch.dict(models.PACKS,fixtures),patch.object(models,'ROOT',app):
                bundled=builder.bundle_model_packs(app,source)
                self.assertEqual(set(bundled),set(fixtures))
                for key,pack in fixtures.items():self.assertEqual(models.source_for(key),(app/'packs'/pack.filename))
                (source/fixtures['da2-base'].filename).write_bytes(b'bad')
                with self.assertRaises(ValueError):builder.bundle_model_packs(root/'other',source)

    def test_default_model_distribution_needs_no_local_pack_and_uses_fixed_public_origin(self):
        from screento3d_app import optional_models as models
        spec=importlib.util.spec_from_file_location('portable_model_distribution',ROOT/'scripts/build-desktop-portable.py')
        builder=importlib.util.module_from_spec(spec);spec.loader.exec_module(builder)
        with tempfile.TemporaryDirectory() as folder:
            app=Path(folder)/'app';app.mkdir()
            metadata=builder.model_distribution(app)
            self.assertFalse((app/'packs').exists())
            self.assertEqual(metadata['bundled_model_packs'],{})
            self.assertEqual(metadata['model_pack_downloads'],models.model_downloads())
            self.assertNotIn('/latest/',(app/'model-origin.txt').read_text())
            with patch.object(models,'ROOT',app):
                for key in models.GRAPH_HASHES:
                    self.assertEqual(models.source_for(key),models.MODEL_ORIGIN+'/'+models.PACKS[key].filename)
            with self.assertRaises(ValueError):builder.model_distribution(app,'http://example.test')

    def test_public_models_are_checked_and_never_added_as_optional_model_asset(self):
        from screento3d_app.optional_models import model_downloads
        with tempfile.TemporaryDirectory() as folder:
            root=Path(folder);app=root/'ScreenTo3D-1.0.0';app.mkdir()
            (app/'build-manifest.json').write_text(json.dumps(dict(product_version='1.0.0',source_commit='fixture',model_pack_downloads=model_downloads())))
            with patch('screento3d_app.upstream_check.check',side_effect=OSError('Model unavailable')),self.assertRaises(OSError):
                packager.package(app,root/'failed',None)
            self.assertFalse((root/'failed').exists())
            with patch('screento3d_app.upstream_check.check',return_value=[dict(component='da2-base',status=206)]) as checked:
                packager.package(app,root/'assets',None)
                checked.assert_called_once_with(model_downloads(),model_downloads())
            manifest=json.loads((root/'assets/release-manifest.json').read_text())
            self.assertTrue(all(asset['kind']=='application' for asset in manifest['assets']))
            self.assertEqual(manifest['model_download_checks'],[dict(component='da2-base',status=206)])
            with self.assertRaisesRegex(ValueError,'separate release'):
                packager.package(app,root/'legacy',root/'packs')
            (app/'packs').mkdir();(app/'packs/unexpected.zip').write_bytes(b'must not ship')
            with self.assertRaisesRegex(ValueError,'accidentally bundle'):
                packager.package(app,root/'leaked',None)


if __name__=='__main__':unittest.main()
