"""Validate Qt catalogs against Python/QML sources and compile bundled translations."""
import argparse
import ast
import json
import importlib.util
from pathlib import Path
import re
from string import Formatter
import subprocess
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
APP=ROOT/'v1/depthsbs_app'
spec=importlib.util.spec_from_file_location('translation_definitions',APP/'catalogs.py')
definitions=importlib.util.module_from_spec(spec)
spec.loader.exec_module(definitions)


def sources():
    result={(context,key) for key in definitions.ERRORS for context in ('Errors','PublicErrors')}
    result.update(('ScreenTo3D',text) for text in ('Error ID','Details','Windows error code','ScreenTo3D launch error'))
    for path in APP.glob('*.py'):
        for node in ast.walk(ast.parse(path.read_text(encoding='utf-8'))):
            if (isinstance(node,ast.Call) and isinstance(node.func,ast.Name) and node.func.id in ('M','Message')
                    and node.args and isinstance(node.args[0],ast.Constant) and isinstance(node.args[0].value,str)):
                result.add(('ScreenTo3D',node.args[0].value))
            if (isinstance(node,ast.Call) and isinstance(node.func,ast.Name) and node.func.id in ('E','ErrorMessage')
                    and node.args and isinstance(node.args[0],ast.Constant)
                    and node.args[0].value not in definitions.ERRORS):
                raise ValueError(f'Unregistered error ID in {path.name}: {node.args[0].value}')
    for path in (APP/'qml').glob('*.qml'):
        for match in re.finditer(r'\bqsTr\(("(?:[^"\\]|\\.)*")\)',path.read_text(encoding='utf-8')):
            result.add((path.stem,json.loads(match[1])))
    return result


def placeholders(text):
    return sorted((name,spec,conversion) for _,name,spec,conversion in Formatter().parse(text) if name is not None)


def read_catalog(path):
    tree=ET.parse(path)
    catalog={}
    for context in tree.getroot().findall('context'):
        name=context.findtext('name')
        for message in context.findall('message'):
            source=message.findtext('source') or ''
            translation=message.find('translation')
            text='' if translation is None else ''.join(translation.itertext())
            if translation is None or translation.get('type')=='unfinished' or not text:
                raise ValueError(f'Unfinished translation: {name}: {source}')
            template=source
            if name in ('Errors','PublicErrors'):
                if source not in definitions.ERRORS:
                    raise ValueError(f'Unregistered translated error ID: {source}')
                template=definitions.ERRORS[source]['public' if name=='PublicErrors' else 'source']
            if placeholders(template)!=placeholders(text):
                raise ValueError(f'Translation placeholders differ: {name}: {source}')
            if (name,source) in catalog:
                raise ValueError(f'Duplicate translation: {name}: {source}')
            catalog[name,source]=text
    missing=sources()-set(catalog)
    if missing:
        raise ValueError('Missing translations:\n'+'\n'.join(f'{context}: {source}' for context,source in sorted(missing)))
    return catalog


def validate(path):
    return len(read_catalog(path))


def update(path,locale):
    """Scaffold new entries; unfinished translations still fail release builds."""
    if path.exists():
        tree=ET.parse(path)
    else:
        tree=ET.ElementTree(ET.Element('TS',version='2.1',language=locale.replace('-','_')))
    root=tree.getroot()
    contexts={c.findtext('name'):c for c in root.findall('context')}
    existing={(c.findtext('name'),m.findtext('source')) for c in root.findall('context') for m in c.findall('message')}
    for context,source in sorted(sources()-existing):
        if context not in contexts:
            contexts[context]=ET.SubElement(root,'context')
            ET.SubElement(contexts[context],'name').text=context
        message=ET.SubElement(contexts[context],'message')
        ET.SubElement(message,'source').text=source
        if context in ('Errors','PublicErrors'):
            ET.SubElement(message,'extracomment').text=definitions.ERRORS[source]['public' if context=='PublicErrors' else 'source']
        ET.SubElement(message,'translation',type='unfinished')
    ET.indent(tree,space='  ')
    tree.write(path,encoding='utf-8',xml_declaration=True)


def native_header(languages,catalogs):
    def wide(text):
        # JSON escaping is valid for these C++ wide string literals; keep Unicode.
        return 'L'+json.dumps(text,ensure_ascii=False)
    keys=['Error ID','Details','Windows error code','ScreenTo3D launch error']
    errors=[key for key,item in definitions.ERRORS.items() if item.get('native')]
    lines=['// Generated by scripts/build-translations.py; edit the registry/catalogs instead.',
           '#pragma once','#include <cstddef>','namespace launcher_i18n {',
           'struct Language { const wchar_t* code; const wchar_t* locale; };',
           'inline constexpr Language languages[] = {']
    lines.extend('    {'+wide(key)+', '+wide(item['locale'])+'},' for key,item in languages.items())
    lines+=['};',f'inline constexpr std::size_t default_language = {list(languages).index(definitions.DEFAULT_LANGUAGE)};',
            'enum Text { ErrorId, Details, WindowsCode, Title, '+', '.join(errors)+' };',
            'inline constexpr const wchar_t* ids[] = {'+', '.join(wide(value) for value in ['', '', '', '', *errors])+'};',
            'inline constexpr const wchar_t* text[][ '+str(len(keys)+len(errors))+' ] = {']
    for code,item in languages.items():
        catalog=catalogs.get(code,{})
        values=[catalog.get(('ScreenTo3D',key),key) for key in keys]
        values.extend(catalog.get(('Errors',key),definitions.ERRORS[key]['source']) for key in errors)
        lines.append('    {'+', '.join(wide(value) for value in values)+'},')
    lines+=['};','} // namespace launcher_i18n','']
    return '\n'.join(lines)


def build(*,check=False,native_only=False,update_catalogs=False):
    _,languages=definitions.load_languages()
    catalogs={}
    for code,item in languages.items():
        if not item['catalog']:
            continue
        path=definitions.DIRECTORY/(item['catalog']+'.ts')
        if update_catalogs:
            update(path,item['locale'])
        if not update_catalogs:
            catalogs[code]=read_catalog(path)
    if update_catalogs:
        return
    header=ROOT/'native/launcher/generated_i18n.h'
    text=native_header(languages,catalogs)
    if check:
        if not header.exists() or header.read_text(encoding='utf-8')!=text:
            raise ValueError('Native translations are stale. Run scripts/build-translations.py.')
    else:
        header.write_text(text,encoding='utf-8')
    if not check and not native_only:
        tool=ROOT/'out/gui-python-deps/PySide6/lrelease.exe'
        if not tool.is_file():
            import PySide6
            tool=Path(PySide6.__file__).parent/'lrelease.exe'
        if not tool.is_file():
            raise FileNotFoundError('PySide6 lrelease.exe is required to build the Qt catalog')
        for code,item in languages.items():
            if item['catalog']:
                path=definitions.DIRECTORY/(item['catalog']+'.ts')
                subprocess.run([str(tool),str(path),'-qm',str(path.with_suffix('.qm'))],check=True)
    print(f'Validated {len(languages)} languages, {len(definitions.ERRORS)} error IDs and {sum(map(len,catalogs.values()))} translations.')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--native-only',action='store_true')
    parser.add_argument('--update',action='store_true',help='Scaffold missing catalog entries for registered languages')
    args=parser.parse_args()
    if args.update and (args.check or args.native_only):
        parser.error('--update cannot be combined with --check or --native-only')
    build(check=args.check,native_only=args.native_only,update_catalogs=args.update)
